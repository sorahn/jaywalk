//! Commands shared by keyboard shortcuts, the command palette, and native menus.
use serde::Deserialize;

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CommandId {
    OpenRepository,
    FindFile,
    ShowCommands,
    OpenSettings,
    VersionPatch,
    SincePrevious,
    Refresh,
    WholeBranch,
    Overview,
    ToggleHistory,
    ToggleFiles,
    ToggleChangeEvolution,
    ToggleFileEvolution,
    ToggleWrap,
    ToggleLineNumbers,
    ViewInline,
    ViewSideBySide,
    ViewFluid,
    NextChange,
    PreviousChange,
    NextFile,
    PreviousFile,
    NextRevision,
    PreviousRevision,
    ZoomIn,
    ZoomOut,
    ResetZoom,
    ResetLayout,
    Quit,
    CloseWindow,
    Minimize,
    Fullscreen,
    Hide,
    HideOthers,
    ShowAll,
}

impl CommandId {
    pub const ALL: &[Self] = &[
        Self::OpenRepository,
        Self::FindFile,
        Self::ShowCommands,
        Self::OpenSettings,
        Self::VersionPatch,
        Self::SincePrevious,
        Self::Refresh,
        Self::WholeBranch,
        Self::Overview,
        Self::ToggleHistory,
        Self::ToggleFiles,
        Self::ToggleChangeEvolution,
        Self::ToggleFileEvolution,
        Self::ToggleWrap,
        Self::ToggleLineNumbers,
        Self::ViewInline,
        Self::ViewSideBySide,
        Self::ViewFluid,
        Self::NextChange,
        Self::PreviousChange,
        Self::NextFile,
        Self::PreviousFile,
        Self::NextRevision,
        Self::PreviousRevision,
        Self::ZoomIn,
        Self::ZoomOut,
        Self::ResetZoom,
        Self::ResetLayout,
        Self::Quit,
        Self::CloseWindow,
        Self::Minimize,
        Self::Fullscreen,
        Self::Hide,
        Self::HideOthers,
        Self::ShowAll,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Self::OpenRepository => "Open repository…",
            Self::FindFile => "Find changed file",
            Self::ShowCommands => "Command palette",
            Self::VersionPatch => "Version patch",
            Self::SincePrevious => "Since previous version",
            Self::OpenSettings => "Open settings",
            Self::Refresh => "Refresh recorded changes",
            Self::WholeBranch => "Whole branch",
            Self::Overview => "Changeset overview",
            Self::ToggleHistory => "Toggle history panel",
            Self::ToggleFiles => "Toggle changed files panel",
            Self::ToggleChangeEvolution => "Toggle change evolution",
            Self::ToggleFileEvolution => "Toggle file evolution",
            Self::ToggleWrap => "Toggle word wrap",
            Self::ToggleLineNumbers => "Toggle line numbers",
            Self::ViewInline => "View: inline",
            Self::ViewSideBySide => "View: side by side",
            Self::ViewFluid => "View: Fluid",
            Self::NextChange => "Next change",
            Self::PreviousChange => "Previous change",
            Self::NextFile => "Next file",
            Self::PreviousFile => "Previous file",
            Self::NextRevision => "Next revision",
            Self::PreviousRevision => "Previous revision",
            Self::ZoomIn => "Increase font size",
            Self::ZoomOut => "Decrease font size",
            Self::ResetZoom => "Reset font size",
            Self::ResetLayout => "Reset panel layout",
            Self::Quit => "Quit Jaywalk",
            Self::CloseWindow => "Close window",
            Self::Minimize => "Minimize",
            Self::Fullscreen => "Toggle full screen",
            Self::Hide => "Hide Jaywalk",
            Self::HideOthers => "Hide others",
            Self::ShowAll => "Show all",
        }
    }
}
